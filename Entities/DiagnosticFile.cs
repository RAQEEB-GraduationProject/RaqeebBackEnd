namespace RAQEEB.Entities
{
    // A private diagnostic document (PDF) stored outside wwwroot.
    // It is only served through the authenticated diagnostics file endpoint.
    public class DiagnosticFile
    {
        public Guid Id { get; set; } = Guid.NewGuid();

        // The patient this document belongs to
        public Guid PatientId { get; set; }

        public Patient Patient { get; set; } = null!;



        // Name shown to / downloaded by the user, e.g. "hemoglobin_2026-11-18.pdf"
        public string FileName { get; set; } = string.Empty;

        public string ContentType { get; set; } = "application/pdf";

        // Path relative to the diagnostics storage root (generated by the server, never by the client)
        public string StoredFileName { get; set; } = string.Empty;

        public long FileSizeBytes { get; set; }

        public DateTime CreatedAt { get; set; } = DateTime.UtcNow;
    }
}
